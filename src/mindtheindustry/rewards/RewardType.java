package mindtheindustry.rewards;

/**
 * Reward categories offered after each wave.
 *
 * TRADEOFF → +X% on one stat, -X% on another (whole group)
 * PLAN     → unlocks building/unit plans for the whole group
 * RESOURCE → resource gift delivered to the team cores
 */
public enum RewardType{
    TRADEOFF,
    PLAN,
    RESOURCE
}
